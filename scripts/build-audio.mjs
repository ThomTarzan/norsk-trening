import { createHash } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { spawn } from "node:child_process";
import { allVocab, lessons } from "../data/catalog.js";
import { pronunciationItems } from "../data/pronunciation.js";
import { readingPlain, readings, sentencesOf } from "../data/readings.js";
import { groupVocab } from "../js/vocab-groups.js";

mkdirSync("audio/setninger", { recursive: true });
mkdirSync("audio/ord", { recursive: true });
mkdirSync("audio/klipp", { recursive: true });
mkdirSync("audio/uttale", { recursive: true });

function norm(text) {
  return String(text || "").replace(/\s+/g, " ").trim();
}

function slug(text) {
  const base = text
    .toLowerCase()
    .replace(/æ/g, "ae")
    .replace(/ø/g, "o")
    .replace(/å/g, "a")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 48);
  const hash = createHash("sha1").update(text).digest("hex").slice(0, 8);
  return `${base || "ord"}-${hash}`;
}

const jobs = [];
const textToPath = new Map();
for (const reading of readings) {
  const sentences = sentencesOf(reading);
  const voices = new Set(sentences.map((sentence) => sentence.voice));
  if (reading.dialogue || voices.size > 1) {
    jobs.push({
      path: reading.audio,
      parts: sentences.map((sentence) => sentence.audio),
      min: 8000,
    });
  } else {
    jobs.push({
      path: reading.audio,
      text: readingPlain(reading),
      voice: reading.voice,
      min: 8000,
    });
  }
  for (const sentence of sentences) {
    jobs.push({
      path: sentence.audio,
      text: sentence.text,
      voice: sentence.voice || reading.voice,
      min: 700,
    });
    textToPath.set(norm(sentence.text), sentence.audio);
  }
}

const groups = groupVocab(allVocab());
const vocabAudio = {};
for (const group of groups) {
  const spoken = group.spoken.replace(/\s+/g, " ").trim();
  const path = `audio/ord/${slug(spoken)}.mp3`;
  for (const id of group.ids) vocabAudio[id] = path;
  jobs.push({ path, text: spoken, voice: "nb-NO-PernilleNeural", min: 400 });
}

const clipAudio = {};
const clipTexts = [];
for (const lesson of lessons) {
  for (const example of lesson.examples) clipTexts.push(example.no);
  for (const word of lesson.vocab) clipTexts.push(word.example);
}
for (const word of allVocab()) clipTexts.push(word.example);
for (const text of clipTexts) {
  const key = norm(text);
  if (!key || clipAudio[key]) continue;
  const reused = textToPath.get(key);
  const path = reused || `audio/klipp/${slug(key)}.mp3`;
  clipAudio[key] = path;
  if (!reused) jobs.push({ path, text: key, voice: "nb-NO-PernilleNeural", min: 400 });
}
for (const item of pronunciationItems()) {
  jobs.push({
    path: `audio/uttale/${item.id}.mp3`,
    text: item.word,
    voice: "nb-NO-PernilleNeural",
    min: 400,
  });
}

const uniqueJobs = [];
const seen = new Set();
for (const job of jobs) {
  if (seen.has(job.path)) continue;
  seen.add(job.path);
  uniqueJobs.push(job);
}

writeFileSync("data/vocab-audio.js", `/** Generated by scripts/build-audio.mjs. Maps every vocabulary id to a bokmål mp3. */\nexport const vocabAudio = ${JSON.stringify(vocabAudio, null, 2)};\n`);
writeFileSync("data/clip-audio.js", `/** Generated by scripts/build-audio.mjs. Maps a Norwegian sentence to a bokmål mp3. */\nexport const clipAudio = ${JSON.stringify(clipAudio, null, 2)};\n`);
writeFileSync("/tmp/norsk-audio-jobs.json", JSON.stringify(uniqueJobs));
console.log(`Queued ${uniqueJobs.length} audio files (${groups.length} ordbank entries, ${Object.keys(clipAudio).length} clips).`);

const python = spawn("python3", ["-"], { stdio: ["pipe", "inherit", "inherit"] });
python.stdin.end(`
import asyncio, json, subprocess
from pathlib import Path
import edge_tts

jobs = json.loads(Path("/tmp/norsk-audio-jobs.json").read_text())

async def one(job, sem):
    path = Path(job["path"])
    if job.get("parts"):
        return "later"
    if path.exists() and path.stat().st_size >= job["min"]:
        return "skip"
    path.parent.mkdir(parents=True, exist_ok=True)
    async with sem:
        last = None
        for attempt in range(5):
            try:
                communicate = edge_tts.Communicate(job["text"], job["voice"], rate="-8%")
                await communicate.save(str(path))
                if path.stat().st_size < job["min"]:
                    raise RuntimeError(f"too small ({path.stat().st_size})")
                print(path, flush=True)
                return "ok"
            except Exception as error:
                last = error
                await asyncio.sleep(1.2 * (attempt + 1))
        raise SystemExit(f"failed {path}: {last}")

def concat(job):
    path = Path(job["path"])
    parts = [Path(part) for part in job["parts"]]
    missing = [part for part in parts if not part.exists()]
    if missing:
        raise SystemExit(f"concat missing parts for {path}: {missing[:3]}")
    if path.exists() and path.stat().st_size >= job["min"]:
        return "skip"
    listing = path.with_suffix(".concat.txt")
    listing.write_text("".join("file '%s'%s" % (part.resolve(), chr(10)) for part in parts), encoding="utf-8")
    cmd = ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(listing), "-c", "copy", str(path)]
    done = subprocess.run(cmd, capture_output=True)
    if done.returncode != 0 or not path.exists() or path.stat().st_size < job["min"]:
        cmd = ["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", str(listing), "-c:a", "libmp3lame", "-q:a", "5", str(path)]
        done = subprocess.run(cmd, capture_output=True)
        if done.returncode != 0:
            raise SystemExit(done.stderr.decode()[-500:])
    listing.unlink(missing_ok=True)
    print(path, flush=True)
    return "ok"

async def main():
    sem = asyncio.Semaphore(4)
    results = await asyncio.gather(*(one(job, sem) for job in jobs))
    concats = [concat(job) for job in jobs if job.get("parts")]
    print(f"done ok={results.count('ok')} skip={results.count('skip')} concat={concats.count('ok')}", flush=True)

asyncio.run(main())
`);

const code = await new Promise((resolve) => python.on("close", resolve));
if (code !== 0) process.exit(code);
